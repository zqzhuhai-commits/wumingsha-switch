#!/usr/bin/env python3
"""Extract declarative data only; never execute upstream JavaScript."""
import json, re
from pathlib import Path
root = Path(__file__).resolve().parents[1]
card = (root / 'upstream/card-standard.js').read_text()
chars = (root / 'upstream/core/character.js').read_text()
translations = (root / 'upstream/core/translate.js').read_text()
supported = ['sha','shan','tao','wuzhong','guohe','shunshou','juedou','nanman','wanjian','taoyuan','zhuge']
enum = ['Sha','Shan','Tao','Wuzhong','Guohe','Shunshou','Juedou','Nanman','Wanjian','Taoyuan','Zhuge']
names = ['杀','闪','桃','无中生有','过河拆桥','顺手牵羊','决斗','南蛮入侵','万箭齐发','桃园结义','诸葛连弩']
entries = re.findall(r'\["(spade|club|heart|diamond)",\s*(\d+),\s*"(\w+)"\]', card[card.index('\n\t\tlist: ['):])
deck = [(supported.index(kind), ['spade','club','heart','diamond'].index(suit), int(rank)) for suit, rank, kind in entries if kind in supported]
assert len(deck) > 70
heroes = ['guanyu','zhangfei','zhaoyun','zhouyu']
hero_data = []
for hero in heroes:
    m = re.search(r'\b'+hero+r':\s*\["\w+",\s*"(\w+)",\s*(\d+),\s*\[([^]]+)\]', chars)
    assert m, hero
    name = re.search(r'\b'+hero+r':\s*"([^"]+)"', translations).group(1)
    hero_data.append({'id':hero,'name':name,'faction':m[1],'hp':int(m[2]),'upstream_skills':re.findall(r'"([^"]+)"',m[3])})
out = '// Generated by tools/import_data.py; GPL-3.0 upstream data.\n#pragma once\n#include <array>\nnamespace noname {\n'
out += 'inline constexpr std::array<Card, '+str(len(deck))+'> standardDeck = {{\n'
out += ''.join('    {Kind::%s, %d, %d, %d},\n' % (enum[k], s, n, uid) for uid,(k,s,n) in enumerate(deck)) + '}};\n'
out += 'inline constexpr const char* cardNames[] = {'+', '.join(json.dumps(n,ensure_ascii=False) for n in names)+'};\n'
out += 'inline constexpr const char* heroIds[] = {'+', '.join(json.dumps(h) for h in heroes)+'};\n'
out += 'inline constexpr const char* heroNames[] = {'+', '.join(json.dumps(h['name'],ensure_ascii=False) for h in hero_data)+'};\n'
out += 'inline constexpr int heroHp[] = {'+', '.join(str(h['hp']) for h in hero_data)+'};\n}\n'
(root/'include/generated_data.hpp').write_text(out)
(root/'upstream/import-summary.json').write_text(json.dumps({'deck_size':len(deck),'supported_cards':supported,'heroes':hero_data},ensure_ascii=False,indent=2)+'\n')
print(f'Imported {len(deck)} cards and {len(hero_data)} heroes')
